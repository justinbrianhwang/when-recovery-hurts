"""Split the manuscript into an editor-ready LaTeX project (e.g. Overleaf): only main.tex and references.bib at the root,
every section in sections/, figures in figures/, tables in tables/, the Supplementary in supplementary/.

The single-file sources in manuscripts/ stay the reference; this script regenerates latex_project/ from them and checks
that the split text equals the original body. (The Elsevier upload package without subfolders is still built by
build.py.)
usage: python -P paper/ras_when_recovery_hurts_001/make_latex_project.py
"""
from __future__ import annotations

import re, shutil
from pathlib import Path

P = Path(__file__).resolve().parent; OUT = P / 'latex_project'
PICK = r'\IfFileExists{tables/T2_development_arms.tex}{\newcommand{\tabdir}{tables/}}{\newcommand{\tabdir}{../tables/}}'


def slug(title):
    return re.sub(r'[^a-z0-9]+', '_', title.lower()).strip('_')[:40]


def split(body, pattern):
    """Split body at every match of pattern (start of a section); returns [(title, text)]."""
    idx = [m.start() for m in re.finditer(pattern, body)]
    parts = []
    for i, a in enumerate(idx):
        text = body[a:idx[i + 1] if i + 1 < len(idx) else len(body)]
        parts.append((re.match(pattern, text).group(1), text))
    return parts


def main_doc():
    s = (P / 'manuscripts/main.tex').read_text(encoding='utf-8')
    a0, a1 = s.index('\\begin{abstract}'), s.index('\\end{keyword}') + len('\\end{keyword}')
    b0 = s.index('%% ----', s.index('\\end{frontmatter}')); b1 = s.index('\\bibliographystyle')
    files = {'sections/00_abstract.tex': s[a0:a1] + '\n'}
    body = s[b0:b1]
    secs = split(body, r'%% -+\n\\section\*?\{([^}]*)\}')
    decl = [x for x in secs if x[0].startswith('CRediT')]
    n = 0
    for title, text in secs:
        if title.startswith('CRediT'): break
        n += 1; files[f'sections/{n:02d}_{slug(title)}.tex'] = text
    d0 = body.index(decl[0][1]); files[f'sections/{n + 1:02d}_declarations.tex'] = body[d0:]
    assert ''.join(v for k, v in files.items() if k != 'sections/00_abstract.tex') == body, 'split lost text'
    head = s[:a0].replace('\\graphicspath{{../figures/}{./}}', '\\graphicspath{{figures/}}').replace('\\newcommand{\\tabdir}{../tables/}', '\\newcommand{\\tabdir}{tables/}')
    main = (head + '\\input{sections/00_abstract}\n\n' + s[a1:b0]
            + ''.join(f'\\input{{{k[:-4]}}}\n' for k in files if k != 'sections/00_abstract.tex')
            + '\n' + s[b1:])
    main = main.replace('% Figures and tables are generated by figures/source_code/make_figures.py and tables/source_code/make_tables.py\n% from the original records; see FIGURE_PROVENANCE.json and TABLE_PROVENANCE.json.',
                        '% Editor-ready project generated by make_latex_project.py from manuscripts/main.tex.\n% Sections in sections/, figures in figures/, tables in tables/, Supplementary in supplementary/.')
    return main, files


def supp_doc():
    s = (P / 'manuscripts/supplementary.tex').read_text(encoding='utf-8')
    b0 = s.index('\\end{frontmatter}') + len('\\end{frontmatter}'); b1 = s.index('\\end{document}')
    body = s[b0:b1]; first = body.index('%% ----')
    files = {'supplementary/sections/S0_overview.tex': body[:first].lstrip('\n')}
    for title, text in split(body[first:], r'%% -+\n\\section\*?\{([^}]*)\}'):
        k = len(files); files[f'supplementary/sections/S{k}_{slug(title)}.tex'] = text
    assert ''.join(files.values()) == body.lstrip('\n')
    head = s[:b0].replace('\\graphicspath{{../figures/}{./}}', '\\graphicspath{{figures/}{../figures/}}').replace('\\newcommand{\\tabdir}{../tables/}', PICK)
    secdir = r'\IfFileExists{supplementary/sections/S0_overview.tex}{\newcommand{\secdir}{supplementary/sections/}}{\newcommand{\secdir}{sections/}}'
    head = head.replace('\\journal{', secdir + '\n\\journal{', 1)
    supp = head + '\n\n' + ''.join(f'\\input{{\\secdir {Path(k).stem}}}\n' for k in files) + '\n\\end{document}\n'
    return supp, files


def main():
    # Since revision round 001 the split project (latex_project/ = Drive Paper/Latex) is the canonical source and is
    # edited directly; regenerating it from manuscripts/ would discard those edits. This script therefore refuses to run
    # over an existing latex_project/. Derive other forms FROM latex_project/ (see export_flat_from_latex.py).
    if OUT.exists(): raise SystemExit('latex_project/ exists and is canonical since revision round 001; refusing to overwrite it')
    main_tex, mfiles = main_doc(); supp_tex, sfiles = supp_doc()
    for k, v in {'main.tex': main_tex, 'supplementary/supplementary.tex': supp_tex, **mfiles, **sfiles}.items():
        f = OUT / k; f.parent.mkdir(parents=True, exist_ok=True); f.write_text(v, encoding='utf-8')
    shutil.copy2(P / 'manuscripts/references.bib', OUT)
    (OUT / 'figures').mkdir(); (OUT / 'tables').mkdir()
    for f in sorted((P / 'figures').glob('*.pdf')): shutil.copy2(f, OUT / 'figures')
    for f in sorted((P / 'tables').glob('T*.tex')): shutil.copy2(f, OUT / 'tables')
    for f in sorted(OUT.rglob('*')): print(f.relative_to(OUT)) if f.is_file() else None


if __name__ == '__main__':
    main()
